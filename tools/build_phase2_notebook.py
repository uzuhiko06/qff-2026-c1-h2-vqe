                "**Definition of Depth:** Here, 'depth' $L$ explicitly denotes the number of entangling repetitions (`reps`) in the Hardware-Efficient Ansatz (HEA: single-qubit $RY$ rotations followed by entangling CX layers).\n",
                "- **Depth 1 ($L=1$):** 4 variational parameters, 1 CX on Processor D, transpiled total depth 9.\n",
                "- **Depth 2 ($L=2$):** 6 variational parameters, 2 CX on Processor D, transpiled total depth 14.\n",
                "\n",
                "**Honest Expressibility Finding:** Because the Parity 2Q Hamiltonian operates in the symmetry-reduced subspace where the ground state is an entangled singlet, Depth 1 already contains sufficient rotational freedom to capture the ground state to machine precision ($0.0000$ mHa with COBYLA, $\\le 0.0012$ mHa with SPSA). Therefore, accuracy is flat across depths 1 and 2, while computational cost and circuit depth rise with depth. Depth 1 is Pareto-optimal."
